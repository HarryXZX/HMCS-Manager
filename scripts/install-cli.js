#!/usr/bin/env node
'use strict';
/**
 * 安装 hmcsm 命令：任意目录敲 `hmcsm` 就能启动控制面板
 *
 *   node scripts/install-cli.js            安装（等价 install）
 *   node scripts/install-cli.js status     看装在哪、是否已经在 PATH 里
 *   node scripts/install-cli.js uninstall  移除
 *
 * 做法：
 *   Windows  → 在 <配置目录>\bin 放一个 hmcsm.cmd，把这个目录追加到「用户」PATH
 *   Linux    → /usr/local/bin/hmcsm（可写时）否则 ~/.local/bin/hmcsm
 *   macOS    → 同上
 *
 * 为什么不是软链接：Windows 上普通用户建符号链接需要开发者模式；
 * 批处理 / sh 各一行，跨平台最省事，出问题也能一眼看明白。
 */
const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const APP = path.join(ROOT, 'app.js');
const NODE = process.execPath;
const IS_WIN = process.platform === 'win32';
const NAME = 'hmcsm';

const c = {
  bold: s => s, dim: s => s, green: s => s, yellow: s => s, cyan: s => s, red: s => s,
};
let useColor = false;
try { useColor = !!process.stdout.isTTY && !process.env.NO_COLOR; } catch { /* ignore */ }
if (useColor) {
  const w = (n, s) => `\u001b[${n}m${s}\u001b[0m`;
  c.bold = s => w('1', s); c.dim = s => w('2', s); c.green = s => w('32', s);
  c.yellow = s => w('33', s); c.cyan = s => w('36', s); c.red = s => w('31', s);
}

const say = s => console.log(s || '');
const ok = s => say('  ' + c.green('✓') + ' ' + s);
const warn = s => say('  ' + c.yellow('!') + ' ' + s);
const bad = s => say('  ' + c.red('×') + ' ' + s);

// ------------------------------------------------------------------ 路径
function configDir() {
  // 与 lib/paths 保持一致：Windows 用 %APPDATA%\HMCS，其它平台按 XDG
  try {
    return require('../lib/paths').CONFIG_DIR;
  } catch {
    if (IS_WIN) return path.join(process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming'), 'HMCS');
    return path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'HMCS');
  }
}

const BIN_DIR_WIN = path.join(configDir(), 'bin');
const LAUNCHER_WIN = path.join(BIN_DIR_WIN, `${NAME}.cmd`);

function canWrite(dir) {
  try {
    fs.accessSync(dir, fs.constants.W_OK);
    return true;
  } catch {
    return false;
  }
}

/** Linux / macOS 落点：优先系统 bin（root 或有权限时），否则用户 bin */
function unixTarget() {
  const candidates = ['/usr/local/bin', path.join(os.homedir(), '.local', 'bin')];
  for (const d of candidates) {
    if (fs.existsSync(d) && canWrite(d)) return d;
  }
  // 目录还不存在但家目录可写，就建 ~/.local/bin
  const local = path.join(os.homedir(), '.local', 'bin');
  try {
    fs.mkdirSync(local, { recursive: true });
    return local;
  } catch {
    return candidates[0];
  }
}

// ------------------------------------------------------------------ 写启动器
/**
 * 批处理必须能被 cmd.exe 解析。
 * 纯 ASCII 内容用 UTF-8 写就是 ASCII，没问题；
 * 路径一旦含中文，cmd.exe 会按系统 ANSI 代码页（简中 936）解读，
 * 这时候用 UTF-8 写进去就是乱码，得交给 PowerShell 转 GBK。
 */
function writeCmdFile(file, text) {
  const crlf = text.replace(/\r?\n/g, '\r\n');
  if (/^[\x00-\x7F]*$/.test(crlf)) {
    fs.writeFileSync(file, crlf, 'ascii');
    return;
  }
  // 先写 UTF-8 临时文件，再让 PowerShell 转码落盘，省得在这条命令里拼 here-string
  const tmp = path.join(os.tmpdir(), `hmcs-launch-${process.pid}-${Date.now()}.txt`);
  fs.writeFileSync(tmp, crlf, 'utf8');
  const q = s => s.replace(/'/g, "''");
  const ps = [
    '$ErrorActionPreference = "Stop"',
    `[IO.File]::WriteAllText('${q(file)}', [IO.File]::ReadAllText('${q(tmp)}', [Text.Encoding]::UTF8), [Text.Encoding]::GetEncoding(936))`,
    `Remove-Item -Force '${q(tmp)}'`,
  ].join('\n');
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8' });
  try { fs.unlinkSync(tmp); } catch { /* 已被 PowerShell 删掉 */ }
  if (r.status !== 0) throw new Error((r.stderr || r.stdout || 'PowerShell 写入失败').trim());
}

function cmdText() {
  return [
    '@echo off',
    'rem ============================================================',
    'rem  HYCX MC Server Manager (HMCS) launcher',
    'rem  Generated by scripts/install-cli.js — delete this file to uninstall.',
    'rem  Usage: hmcsm [--port 8720] [--host 127.0.0.1] [--help]',
    'rem ============================================================',
    'setlocal',
    'if "%~1"=="--help" goto help',
    'if "%~1"=="-h" goto help',
    // 优先用 PATH 里的 node：用户升级 / 换成 nvm 之后还能跟着走。
    // 找不到（用安装包自带的 node 装的环境）才退回安装时的绝对路径。
    'where node >nul 2>&1',
    'if errorlevel 1 goto fallback',
    'node "' + APP + '" %*',
    'exit /b %ERRORLEVEL%',
    ':fallback',
    `set "HMCS_NODE=${NODE}"`,
    'if not exist "%HMCS_NODE%" set "HMCS_NODE=node"',
    '"%HMCS_NODE%" "' + APP + '" %*',
    'exit /b %ERRORLEVEL%',
    ':help',
    'echo HMCS - HYCX MC Server Manager',
    'echo.',
    'echo   hmcsm                 启动控制面板（读取已保存的端口和监听地址）',
    'echo   hmcsm --port 8720     临时指定端口',
    'echo   hmcsm --host 0.0.0.0  临时允许外部访问（需要先设密码）',
    'echo.',
    'echo 配置目录: ' + configDir(),
    'echo 程序目录: ' + ROOT,
    'exit /b 0',
    '',
  ].join('\r\n');
}

function shText() {
  return [
    '#!/bin/sh',
    '# ============================================================',
    '#  HYCX MC Server Manager (HMCS) launcher',
    '#  Generated by scripts/install-cli.js — delete this file to uninstall.',
    '#  Usage: hmcsm [--port 8720] [--host 127.0.0.1] [--help]',
    '# ============================================================',
    'case "$1" in',
    '  --help|-h)',
    '    echo "HMCS - HYCX MC Server Manager"',
    '    echo',
    '    echo "  hmcsm                 启动控制面板（读取已保存的端口和监听地址）"',
    '    echo "  hmcsm --port 8720     临时指定端口"',
    '    echo "  hmcsm --host 0.0.0.0  临时允许外部访问（需要先设密码）"',
    '    echo',
    `    echo "配置目录: ${configDir()}"`,
    `    echo "程序目录: ${ROOT}"`,
    '    exit 0',
    '    ;;',
    'esac',
    // 优先用 PATH 里的 node（nvm / 发行版包），找不到才用安装时记录的绝对路径
    'if command -v node >/dev/null 2>&1; then',
    `  exec node "${APP}" "$@"`,
    'fi',
    `HMCS_NODE="${NODE}"`,
    '[ -x "$HMCS_NODE" ] || HMCS_NODE=node',
    `exec "$HMCS_NODE" "${APP}" "$@"`,
    '',
  ].join('\n');
}

// ------------------------------------------------------------------ PATH
function winUserPathRaw() {
  const ps = [
    '$v = (Get-ItemProperty -Path \'HKCU:\\Environment\' -Name Path -ErrorAction SilentlyContinue).Path',
    "if ($null -eq $v) { '' } else { $v }",
  ].join('; ');
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8' });
  return r.status === 0 ? String(r.stdout || '').trim() : '';
}

function winPathHas(dir) {
  const norm = s => s.trim().replace(/[\\/]+$/, '').toLowerCase();
  const target = norm(dir);
  return winUserPathRaw().split(';').some(x => x.trim() && norm(x) === target);
}

/**
 * 把目录追加进「用户」PATH。
 * 直接改 HKCU:\Environment 的 Path（REG_EXPAND_SZ），而不是用 setx：
 *   - setx 会把 %JAVA_HOME%\bin 这类变量展开成当时的绝对路径，之后就再也不跟手了；
 *   - setx 还有 1024 字符截断的老毛病，PATH 长的机器会直接被砍断。
 */
function winAddPath(dir) {
  if (winPathHas(dir)) return false;
  const q = dir.replace(/'/g, "''");
  const ps = [
    '$ErrorActionPreference = "Stop"',
    "$key = 'HKCU:\\Environment'",
    '$cur = (Get-ItemProperty -Path $key -Name Path -ErrorAction SilentlyContinue).Path',
    "if ($null -eq $cur) { $cur = '' }",
    `$add = '${q}'`,
    '$parts = @($cur -split \';\' | Where-Object { $_ -ne \'\' })',
    'if ($parts -notcontains $add) {',
    '  $new = (@($parts) + $add) -join \';\'',
    '  Set-ItemProperty -Path $key -Name Path -Value $new -Type ExpandString',
    '  $sig = \'[DllImport("user32.dll",SetLastError=true,CharSet=CharSet.Auto)]public static extern IntPtr SendMessageTimeout(IntPtr hWnd,uint Msg,UIntPtr wParam,string lParam,uint fuFlags,uint uTimeout,out UIntPtr lpdwResult);\'',
    '  $t = Add-Type -MemberDefinition $sig -Name U32 -Namespace Win -PassThru',
    '  $r = [UIntPtr]::Zero',
    '  [void]$t::SendMessageTimeout([IntPtr]0xffff, 0x1A, [UIntPtr]::Zero, \'Environment\', 2, 3000, [ref]$r)',
    "  Write-Output 'ADDED'",
    "} else { Write-Output 'EXISTS' }",
  ].join('\n');
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error((r.stderr || r.stdout || '修改 PATH 失败').trim());
  return /ADDED/.test(r.stdout || '');
}

function winRemovePath(dir) {
  const q = dir.replace(/'/g, "''");
  const ps = [
    '$ErrorActionPreference = "Stop"',
    "$key = 'HKCU:\\Environment'",
    '$cur = (Get-ItemProperty -Path $key -Name Path -ErrorAction SilentlyContinue).Path',
    'if ($null -eq $cur) { exit 0 }',
    `$del = '${q}'`,
    '$parts = @($cur -split \';\' | Where-Object { $_ -ne \'\' -and $_ -ne $del })',
    '$new = $parts -join \';\'',
    'Set-ItemProperty -Path $key -Name Path -Value $new -Type ExpandString',
    "Write-Output 'REMOVED'",
  ].join('\n');
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8' });
  return r.status === 0;
}

function unixPathHas(dir) {
  return (process.env.PATH || '').split(':').filter(Boolean).includes(dir);
}

function rcFile() {
  const shell = process.env.SHELL || '';
  const home = os.homedir();
  if (shell.includes('zsh')) return path.join(home, '.zshrc');
  if (shell.includes('bash')) return path.join(home, '.bashrc');
  return path.join(home, '.profile');
}

function unixAddPath(dir) {
  if (unixPathHas(dir)) return null;
  const rc = rcFile();
  const cur = fs.existsSync(rc) ? fs.readFileSync(rc, 'utf8') : '';
  if (cur.includes(`export PATH="${dir}:$PATH"`)) return null;
  fs.appendFileSync(rc, `\n# HMCS 控制台命令（由 install-cli.js 添加）\nexport PATH="${dir}:$PATH"\n`, 'utf8');
  return rc;
}

function unixRemovePath(dir) {
  const rc = rcFile();
  if (!fs.existsSync(rc)) return false;
  const cur = fs.readFileSync(rc, 'utf8');
  const next = cur
    .replace(`\n# HMCS 控制台命令（由 install-cli.js 添加）\nexport PATH="${dir}:$PATH"\n`, '\n')
    .replace(`export PATH="${dir}:$PATH"\n`, '');
  if (next === cur) return false;
  fs.writeFileSync(rc, next, 'utf8');
  return true;
}

// ------------------------------------------------------------------ 命令
function line() { say('  ' + '─'.repeat(58)); }

function cmdInstall() {
  line();
  say('  ' + c.bold('安装 hmcsm 命令'));
  line();
  say('  程序      ' + APP);
  say('  Node      ' + NODE);
  say('');

  if (!fs.existsSync(APP)) {
    bad('找不到 ' + APP);
    process.exit(1);
  }

  if (IS_WIN) {
    fs.mkdirSync(BIN_DIR_WIN, { recursive: true });
    writeCmdFile(LAUNCHER_WIN, cmdText());
    ok('已写入    ' + LAUNCHER_WIN);
    const added = winAddPath(BIN_DIR_WIN);
    if (added) ok('已加入用户 PATH：' + BIN_DIR_WIN);
    else if (winPathHas(BIN_DIR_WIN)) ok('用户 PATH 里已经有这个目录');
    else warn('未能确认 PATH 写入，请手动把 ' + BIN_DIR_WIN + ' 加进 PATH');
    say('');
    say('  ' + c.cyan('新开一个命令行窗口') + '（当前窗口读的还是旧 PATH），然后：');
    say('      ' + c.bold('hmcsm'));
    say('      ' + c.dim('hmcsm --port 8720   临时换端口'));
  } else {
    const dir = unixTarget();
    if (!dir || !canWrite(dir)) {
      bad('没有可写的目录。用 sudo 运行本脚本，或手动把启动器放到 PATH 里。');
      process.exit(1);
    }
    const target = path.join(dir, NAME);
    fs.writeFileSync(target, shText(), 'utf8');
    fs.chmodSync(target, 0o755);
    ok('已写入    ' + target);
    const rc = unixAddPath(dir);
    if (rc) ok('已把 ' + dir + ' 加入 PATH（写在 ' + rc + '）');
    else if (unixPathHas(dir)) ok('PATH 里已经有 ' + dir);
    say('');
    say('  ' + c.cyan('重开终端') + '（或 source 一下配置文件），然后：');
    say('      ' + c.bold('hmcsm'));
    say('      ' + c.dim('hmcsm --port 8720   临时换端口'));
  }
  say('');
}

function cmdStatus() {
  line();
  say('  ' + c.bold('hmcsm 命令状态'));
  line();
  const target = IS_WIN ? LAUNCHER_WIN : path.join(unixTarget() || '', NAME);
  const exists = !!target && fs.existsSync(target);
  const inPath = exists && (IS_WIN ? winPathHas(BIN_DIR_WIN) : unixPathHas(path.dirname(target)));
  say('  启动器    ' + (exists ? c.green(target) : c.dim('未安装')));
  say('  PATH      ' + (exists ? (inPath ? c.green('已包含') : c.yellow('未包含')) : c.dim('—（安装后自动处理）')));
  say('  程序      ' + APP);
  say('  Node      ' + NODE);
  say('');
  if (!exists) say('  运行 ' + c.cyan('node scripts/install-cli.js install') + ' 安装');
  else if (!inPath) warn('启动器在，但所在目录不在 PATH 里，新开终端也敲不出来');
  say('');
}

function cmdUninstall() {
  line();
  say('  ' + c.bold('移除 hmcsm 命令'));
  line();
  if (IS_WIN) {
    if (fs.existsSync(LAUNCHER_WIN)) {
      fs.unlinkSync(LAUNCHER_WIN);
      ok('已删除 ' + LAUNCHER_WIN);
    } else warn('启动器本来就不存在');
    if (winRemovePath(BIN_DIR_WIN)) ok('已从用户 PATH 移除 ' + BIN_DIR_WIN);
    try {
      if (fs.existsSync(BIN_DIR_WIN) && fs.readdirSync(BIN_DIR_WIN).length === 0) fs.rmdirSync(BIN_DIR_WIN);
    } catch { /* 目录非空或占用就算了 */ }
  } else {
    const dir = unixTarget();
    const target = path.join(dir || '', NAME);
    if (fs.existsSync(target)) {
      fs.unlinkSync(target);
      ok('已删除 ' + target);
    } else warn('启动器本来就不存在');
    if (unixRemovePath(dir)) ok('已从 ' + rcFile() + ' 里移除 PATH 设置');
  }
  say('');
}

const cmd = (process.argv[2] || 'install').toLowerCase();
const table = { install: cmdInstall, status: cmdStatus, uninstall: cmdUninstall };
if (!table[cmd]) {
  say('用法: node scripts/install-cli.js [install|status|uninstall]');
  process.exit(1);
}
try {
  table[cmd]();
} catch (e) {
  bad(e.message || String(e));
  process.exit(1);
}
